  function normalize(value) {
    if (!value) return null;
    const locale = String(value).trim().replace(/_/g, "-").toLowerCase();
    if (locale === "en" || locale.startsWith("en-")) return "en";
    if (locale === "zh" || locale.startsWith("zh-")) return "zh-CN";
    return null;
  }

  function savedLocale() {
    try { return normalize(root.localStorage?.getItem(STORAGE_KEY)); } catch { return null; }
  }

  function resolveLocale() {
    let query = null;
    try { query = normalize(new URLSearchParams(root.location?.search || "").get("lang")); } catch {}
    if (query) return query;
    const saved = savedLocale();
    if (saved) return saved;
    const browserLocales = root.navigator?.languages || [root.navigator?.language];
    for (const value of browserLocales || []) {
      const locale = normalize(value);
      if (locale) return locale;
    }
    return "zh-CN";
  }

  let locale = resolveLocale();

  function t(key, values = {}) {
    const template = catalogs[locale]?.[key] ?? catalogs["zh-CN"][key] ?? key;
    return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) => values[name] == null ? "" : String(values[name]));
  }

  function applyStatic(scope) {
    const doc = root.document;
    if (!doc) return;
    const target = scope || doc;
    doc.documentElement.lang = locale;
    doc.title = t("app.title");
    const description = doc.querySelector('meta[name="description"]');
    if (description) description.content = t("app.description");
    target.querySelectorAll?.("[data-i18n]").forEach((node) => { node.textContent = t(node.dataset.i18n); });
    for (const attribute of ["aria-label", "title", "placeholder"]) {
      const dataName = `data-i18n-${attribute}`;
      target.querySelectorAll?.(`[${dataName}]`).forEach((node) => node.setAttribute(attribute, t(node.getAttribute(dataName))));
    }
  }

  function setLocale(value, options = {}) {
    const next = normalize(value);
    if (!next) throw new Error(`Unsupported locale: ${value}`);
    locale = next;
    if (options.persist !== false) {
      try { root.localStorage?.setItem(STORAGE_KEY, locale); } catch {}
    }
    if (options.updateURL !== false && root.history && root.location) {
      const url = new URL(root.location.href);
      url.searchParams.set("lang", locale);
      root.history.replaceState(root.history.state, "", `${url.pathname}${url.search}${url.hash}`);
    }
    applyStatic();
    root.dispatchEvent?.(new CustomEvent("codex-usage-locale-change", { detail: { locale } }));
    return locale;
  }

  function formatNumber(value, options) {
    return Number(value || 0).toLocaleString(locale, options);
  }

  function formatDate(value, options) {
    const date = value instanceof Date ? value : new Date(value);
    return date.toLocaleDateString(locale, options);
  }

  function formatDateTime(value, options = {}) {
    const date = value instanceof Date ? value : new Date(value);
    return date.toLocaleString(locale, { hour12: false, ...options });
  }

